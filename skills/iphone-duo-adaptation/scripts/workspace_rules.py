#!/usr/bin/env python3
"""Materialize the bundled catalog in a target workspace; no third-party packages.

This validates traceability and local files, not Apple compliance or visual quality.
"""
from __future__ import annotations

import argparse
from collections import Counter
import hashlib
import html
import json
import os
from pathlib import Path, PureWindowsPath
import re
import sys
import tempfile


CATALOG = Path(__file__).resolve().parents[1] / "assets/official-rules.json"
DEFAULT_OUTPUT = "docs/iphone-duo-adaptation"
GENERATED = "<!-- Generated by iphone-duo-adaptation workspace_rules.py; edit workspace-rules.json and run render. -->"
KINDS = {"apple_guidance", "flutter_contract", "engineering_constraint", "product_choice", "workflow_constraint"}
PHASES = {"layout_analysis", "adaptation_recommendations", "html_prototype", "native_implementation"}
STATUSES = {"pending", "implemented", "verified", "not_applicable", "deferred", "blocked"}
PROJECT_ORIGINS = {"user_instruction", "project_contract", "product_decision"}
IDENTIFIER = re.compile(r"[A-Za-z][A-Za-z0-9]*(?:[-_][A-Za-z0-9]+)*\Z")


class RuleError(ValueError):
    """A readable validation failure, with no file changes."""


def require(condition, message):
    if not condition:
        raise RuleError(message)


def nonempty(value):
    return isinstance(value, str) and bool(value.strip())


def unique_object(pairs):
    result = {}
    for key, value in pairs:
        require(key not in result, "Duplicate JSON object key: " + key)
        result[key] = value
    return result


def read_json(path):
    require(path.is_file(), "Missing JSON file: " + str(path))
    raw = path.read_bytes()
    try:
        data = json.loads(raw, object_pairs_hook=unique_object)
    except (UnicodeDecodeError, json.JSONDecodeError) as error:
        raise RuleError("Invalid JSON in {}: {}".format(path, error)) from error
    return data, raw


def string_list(value, label, allowed=None, empty=False):
    require(isinstance(value, list), label + " must be an array")
    require(empty or bool(value), label + " must not be empty")
    require(all(nonempty(item) for item in value), label + " must contain nonempty strings")
    require(len(set(value)) == len(value), label + " contains duplicates")
    if allowed is not None:
        require(set(value) <= allowed, label + " contains unknown values")


def load_catalog(path=CATALOG):
    catalog, raw = read_json(Path(path))
    require(isinstance(catalog, dict), "Catalog must be an object")
    require(type(catalog.get("schema_version")) is int and catalog["schema_version"] == 1,
            "Unsupported catalog schema_version")
    require(nonempty(catalog.get("checked_at")), "Catalog checked_at is required")
    source_ids = set()
    sources = catalog.get("sources")
    require(isinstance(sources, list) and bool(sources), "Catalog sources must be a nonempty array")
    for source in sources:
        require(isinstance(source, dict), "Each source must be an object")
        require(all(nonempty(source.get(key)) for key in ("id", "title", "url", "checked_at")),
                "Source id, title, url and checked_at must be nonempty strings")
        require(IDENTIFIER.fullmatch(source["id"]), "Invalid source id: " + source["id"])
        require(source["id"] not in source_ids, "Duplicate source id: " + source["id"])
        source_ids.add(source["id"])
    rules = catalog.get("rules")
    require(isinstance(rules, list) and bool(rules), "Catalog rules must be a nonempty array")
    rule_ids = set()
    for rule in rules:
        require(isinstance(rule, dict), "Each rule must be an object")
        require(all(nonempty(rule.get(key)) for key in (
            "id", "title", "kind", "applies_when", "statement", "workspace_action", "verification")),
            "Every rule requires nonempty id/title/kind/applies_when/statement/workspace_action/verification")
        require(IDENTIFIER.fullmatch(rule["id"]), "Invalid rule id: " + rule["id"])
        require(rule["id"] not in rule_ids, "Duplicate catalog rule id: " + rule["id"])
        rule_ids.add(rule["id"])
        require(rule["kind"] in KINDS, "Unknown rule kind: " + rule["kind"])
        string_list(rule.get("phases"), rule["id"] + " phases", PHASES)
        string_list(rule.get("source_ids"), rule["id"] + " source_ids", source_ids)
    return catalog, hashlib.sha256(raw).hexdigest()


def workspace_root(workspace):
    root = Path(workspace).resolve()
    require(root.is_dir(), "Workspace must be an existing directory: " + str(root))
    return root


def local_path(root, value, label, must_exist=False, file_only=False):
    require(nonempty(value), label + " requires a relative path")
    require("\\" not in value and "\0" not in value, label + " must use workspace-relative POSIX paths")
    path = Path(value)
    require(not path.is_absolute() and not PureWindowsPath(value).drive and ".." not in path.parts,
            label + " cannot be absolute or contain '..': " + value)
    require(value not in {".", "./"}, label + " must name a workspace entry")
    candidate = root / path
    try:
        resolved = candidate.resolve()
    except (OSError, RuntimeError) as error:
        raise RuleError(label + " cannot resolve safely: " + value) from error
    require(resolved.is_relative_to(root), label + " escapes workspace through a symbolic link: " + value)
    if must_exist:
        require(candidate.exists(), label + " does not exist: " + value)
    if file_only:
        require(candidate.is_file(), label + " must be an existing file: " + value)
    return candidate


def output_paths(root, output_dir=DEFAULT_OUTPUT):
    directory = local_path(root, output_dir, "Output directory")
    require(not directory.exists() or directory.is_dir(), "Output directory is not a directory")
    paths = [local_path(root, str(Path(output_dir) / name), "Output path")
             for name in ("workspace-rules.json", "workspace-rules.md")]
    for path in paths:
        require(not path.is_symlink(), "Output files must not be symbolic links: " + str(path))
        require(not path.exists() or path.is_file(), "Output path is not a file: " + str(path))
    return paths


def validate_binding(binding, rule_id, phases, root, complete=False):
    """Apply identical status/evidence gates to general rules and project conventions."""
    status = binding.get("status")
    require(isinstance(status, str) and status in STATUSES, "Invalid status for " + rule_id)
    for key in ("reason", "decision"):
        require(isinstance(binding.get(key), str), rule_id + " " + key + " must be a string")
    for key in ("targets", "evidence"):
        string_list(binding.get(key), rule_id + " " + key, empty=True)
        for value in binding[key]:
            local_path(root, value, rule_id + " " + key,
                       must_exist=status in {"implemented", "verified"},
                       file_only=key == "evidence" and status == "verified")
    if status in {"not_applicable", "deferred", "blocked"}:
        require(nonempty(binding["reason"]), rule_id + " requires a reason for " + status)
    if status in {"implemented", "verified"}:
        require(nonempty(binding["decision"]) and bool(binding["targets"]),
                rule_id + " requires a decision and existing targets for " + status)
    if status == "verified":
        require(bool(binding["evidence"]), rule_id + " verified requires existing evidence files")
    if complete:
        require(status not in {"pending", "blocked", "implemented"},
                rule_id + " is not complete: " + status)
        if status == "deferred":
            require(set(phases) == {"native_implementation"},
                    rule_id + " cannot defer a non-native-only rule at completion")
    return status


def validate_ledger(ledger, catalog, digest, root, complete=False):
    require(isinstance(ledger, dict), "Workspace ledger must be an object")
    require(type(ledger.get("schema_version")) is int and ledger["schema_version"] == 1,
            "Unsupported workspace schema_version")
    require(ledger.get("catalog_sha256") == digest,
            "Catalog SHA-256 differs; reconcile the current catalog explicitly before rendering/checking")
    for key in ("checked_at", "sources", "rules"):
        require(ledger.get(key) == catalog[key], "Workspace " + key + " differs from the complete canonical catalog")
    rules = {rule["id"]: rule for rule in catalog["rules"]}
    bindings = ledger.get("bindings")
    require(isinstance(bindings, list), "bindings must be an array")
    ids = []
    counts = Counter()
    for binding in bindings:
        require(isinstance(binding, dict), "Each binding must be an object")
        rule_id = binding.get("rule_id")
        require(isinstance(rule_id, str) and rule_id in rules, "Unknown binding rule_id: " + str(rule_id))
        ids.append(rule_id)
        status = validate_binding(binding, rule_id, rules[rule_id]["phases"], root, complete)
        counts[status] += 1
    require(len(ids) == len(set(ids)), "Duplicate rule bindings")
    missing = set(rules) - set(ids)
    require(not missing, "Missing rule bindings: " + ", ".join(sorted(missing)))
    projects = ledger.get("project_conventions", [])
    require(isinstance(projects, list), "project_conventions must be an array")
    project_ids = set()
    for project in projects:
        require(isinstance(project, dict), "Each project convention must be an object")
        project_id = project.get("id")
        require(nonempty(project_id) and project_id.startswith("PROJECT-") and IDENTIFIER.fullmatch(project_id),
                "Project convention id must be a stable ASCII PROJECT- identifier: " + str(project_id))
        require(project_id not in rules, "Project convention id shadows a canonical rule: " + project_id)
        require(project_id not in project_ids, "Duplicate project convention id: " + project_id)
        project_ids.add(project_id)
        for key in ("title", "basis", "applies_when", "statement"):
            require(nonempty(project.get(key)), project_id + " " + key + " must be a nonempty string")
        require(isinstance(project.get("origin"), str) and project["origin"] in PROJECT_ORIGINS,
                project_id + " origin must identify a user_instruction, project_contract or product_decision; "
                "project conventions are not official guidance")
        string_list(project.get("phases"), project_id + " phases", PHASES)
        string_list(project.get("parent_rule_ids"), project_id + " parent_rule_ids", set(rules), empty=True)
        status = validate_binding(project, project_id, project["phases"], root, complete)
        counts[status] += 1
    return counts


def markdown(ledger):
    def cell(value):
        return html.escape(str(value), quote=False).replace("|", "\\|").replace("\n", "<br>")

    semantic_hash = hashlib.sha256(json.dumps(ledger, sort_keys=True, ensure_ascii=False,
                                             separators=(",", ":")).encode()).hexdigest()
    lines = [GENERATED, "<!-- ledger-sha256: " + semantic_hash + " -->", "",
             "# iPhone Duo workspace rule implementation ledger", "",
             "General rules retain the complete canonical snapshot. Project conventions record user instructions, project contracts and product choices separately; they are not Apple requirements. "
             "pending means not yet implemented. Structural checks do not establish Apple compliance, visual quality or native acceptance.", "",
             "- Catalog check date: " + cell(ledger["checked_at"]),
             "- Catalog SHA-256: `" + ledger["catalog_sha256"] + "`",
             "- General rules: {}; project conventions: {}".format(len(ledger["rules"]),
                                                len(ledger.get("project_conventions", []))),
             "", "## Sources", ""]
    for source in ledger["sources"]:
        lines.append("- **{}** — {} — {} — {}".format(
            cell(source["id"]), cell(source["title"]), cell(source["url"]), cell(source["checked_at"])))
    bindings = {binding["rule_id"]: binding for binding in ledger["bindings"]}
    lines.extend(["", "## General rules", ""])
    for rule in ledger["rules"]:
        binding = bindings[rule["id"]]
        lines.extend(["", "### " + cell(rule["id"]) + " · " + cell(rule["title"]), "",
                      "| Field | Rule and implementation |", "| --- | --- |"])
        for label, value in (
            ("Kind", rule["kind"]), ("Phases", ", ".join(rule["phases"])),
            ("Applies when", rule["applies_when"]), ("Rule / guidance / recommendation", rule["statement"]),
            ("Workspace action", rule["workspace_action"]), ("Verification method", rule["verification"]),
            ("Source IDs", ", ".join(rule["source_ids"])), ("Status", binding["status"]),
            ("Adaptation decision", binding["decision"]), ("Reason / gap", binding["reason"]),
            ("Workspace targets", ", ".join(binding["targets"])), ("Verification evidence", ", ".join(binding["evidence"]))):
            lines.append("| {} | {} |".format(label, cell(value)))
    lines.extend(["", "## Project conventions", "",
                  "These are project-specific choices and implementation records. They do not alter general rules or represent Apple requirements."])
    projects = ledger.get("project_conventions", [])
    if not projects:
        lines.extend(["", "No project conventions recorded."])
    for project in projects:
        lines.extend(["", "### " + cell(project["id"]) + " · " + cell(project["title"]), "",
                      "| Field | Project convention and implementation |", "| --- | --- |"])
        for label, value in (
            ("Origin", project["origin"]), ("Project basis", project["basis"]),
            ("Parent general-rule IDs", ", ".join(project["parent_rule_ids"])),
            ("Phases", ", ".join(project["phases"])), ("Applies when", project["applies_when"]),
            ("Project convention", project["statement"]), ("Status", project["status"]),
            ("Adaptation decision", project["decision"]), ("Reason / gap", project["reason"]),
            ("Workspace targets", ", ".join(project["targets"])), ("Verification evidence", ", ".join(project["evidence"]))):
            lines.append("| {} | {} |".format(label, cell(value)))
    return "\n".join(lines) + "\n"


def require_generated(path):
    if path.exists():
        require(path.read_text(encoding="utf-8").startswith(GENERATED + "\n"),
                "Refusing to overwrite non-generated Markdown: " + str(path))


def write_outputs(contents, exclusive=False):
    """Prepare every file before publishing; roll back an interrupted init pair."""
    prepared = []
    published = []
    created_dirs = []
    try:
        for path, content in contents:
            if exclusive:
                require(not path.exists(), "Already exists; preserved without changes: " + str(path))
            missing = []
            parent = path.parent
            while not parent.exists():
                missing.append(parent)
                parent = parent.parent
            for directory in reversed(missing):
                directory.mkdir()
                created_dirs.append(directory)
            descriptor, name = tempfile.mkstemp(prefix=".workspace-rules-", dir=path.parent)
            temporary = Path(name)
            prepared.append((temporary, path))
            with os.fdopen(descriptor, "w", encoding="utf-8", newline="\n") as stream:
                stream.write(content)
                stream.flush()
                os.fsync(stream.fileno())
        for temporary, path in prepared:
            if exclusive:
                # Same-directory hard links publish exclusively, never clobbering user files.
                os.link(temporary, path)
                published.append(path)
                temporary.unlink()
            else:
                os.replace(temporary, path)
    except Exception:
        if exclusive:
            for path in reversed(published):
                path.unlink()
        raise
    finally:
        for temporary, _ in prepared:
            if temporary.exists():
                temporary.unlink()
        for directory in reversed(created_dirs):
            try:
                directory.rmdir()
            except OSError:
                pass


def run(command, workspace, output_dir=DEFAULT_OUTPUT, complete=False, catalog_path=CATALOG):
    require(command in {"init", "render", "check"}, "Unknown command: " + command)
    require(not complete or command == "check", "--complete is supported only with check")
    root = workspace_root(workspace)
    json_path, md_path = output_paths(root, output_dir)
    catalog, digest = load_catalog(catalog_path)
    if command == "init":
        for path in (json_path, md_path):
            require(not path.exists(), "Already exists; preserved without changes: " + str(path))
        ledger = {"schema_version": 1, "catalog_sha256": digest,
                  "checked_at": catalog["checked_at"], "sources": catalog["sources"], "rules": catalog["rules"],
                  "bindings": [{"rule_id": rule["id"], "status": "pending", "reason": "", "decision": "",
                                "targets": [], "evidence": []} for rule in catalog["rules"]],
                  "project_conventions": []}
        counts = validate_ledger(ledger, catalog, digest, root)
        write_outputs([(json_path, json.dumps(ledger, ensure_ascii=False, indent=2) + "\n"),
                       (md_path, markdown(ledger))], exclusive=True)
    else:
        ledger, _ = read_json(json_path)
        counts = validate_ledger(ledger, catalog, digest, root, complete=complete)
        expected = markdown(ledger)
        if command == "render":
            require_generated(md_path)
            write_outputs([(md_path, expected)])
        else:
            require(md_path.is_file(), "Missing Markdown file; run render: " + str(md_path))
            require(md_path.read_text(encoding="utf-8") == expected,
                    "Stale or edited Markdown; reconcile the JSON and run render")
    summary = ", ".join("{}={}".format(status, counts[status]) for status in sorted(counts))
    project_count = len(ledger.get("project_conventions", []))
    return ("{}: general={}, project={} ({})\n{}\nStructural traceability only; this does not establish Apple compliance, "
            "visual quality or native acceptance.{}".format(
                command, len(catalog["rules"]), project_count, summary, md_path,
                " Pending rules do not represent completion." if counts["pending"] else ""))


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=("init", "render", "check"))
    parser.add_argument("--workspace", required=True, help="existing target workspace directory")
    parser.add_argument("--output-dir", default=DEFAULT_OUTPUT, help="workspace-relative output directory")
    parser.add_argument("--complete", action="store_true", help="require completed non-native rules (check only)")
    args = parser.parse_args(argv)
    try:
        print(run(args.command, args.workspace, args.output_dir, args.complete))
    except (RuleError, OSError, RuntimeError, UnicodeError) as error:
        print("ERROR: " + str(error), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
